#!/usr/bin/env python3
"""Check Shortcuts discovery in a built app and its embedded widget extension.

Failure analysis: widget button intents default to discoverable, so Shortcuts
lists them alongside the app's playback actions (including translated duplicates).
Hiding the app actions instead would remove the supported Shortcuts interface;
deleting widget intents would break widget buttons or saved references.

The real Shortcuts picker reproduces this bug, but its paginated, localized UI
cannot verify the complete exported catalog or the continued existence of hidden
widget intents. This supplementary artifact check exercises Xcode's actual
metadata output, not source spelling. Retain --evidence alongside UI screenshots.
"""

import argparse
import hashlib
import json
from pathlib import Path
import platform
import re
import shlex
import subprocess
import sys


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("app", type=Path)
parser.add_argument("--evidence", required=True, type=Path)
args = parser.parse_args()
app = args.app.resolve()
widget = app / "PlugIns/InstacastWidgets.appex"
metadata = {}
paths = {}
for name, bundle in (("app", app), ("widget", widget)):
    path = bundle / "Metadata.appintents/extract.actionsdata"
    data = path.read_bytes()
    paths[name] = {"path": str(path), "sha256": hashlib.sha256(data).hexdigest()}
    metadata[name] = json.loads(data)["actions"]

widget_controls = {
    "PlayPauseIntent", "SkipForwardIntent", "SkipBackwardIntent",
    "NextChapterIntent", "PrevChapterIntent", "NextEpisodeIntent",
    "PrevEpisodeIntent", "CycleSpeedIntent", "ToggleSleepTimerIntent",
    "SkipToChapterIntent",
}
public_controls = {
    "ICPlayIntent", "ICPauseIntent", "ICPlayPauseIntent",
    "ICSkipForwardIntent", "ICSkipBackwardIntent", "ICNextChapterIntent",
    "ICPreviousChapterIntent", "ICNextEpisodeIntent", "ICPreviousEpisodeIntent",
    "ICCyclePlaybackSpeedIntent", "ICSetPlaybackSpeedIntent",
    "ICSetSleepTimerIntent", "ICCancelSleepTimerIntent",
    "ICMarkPlayedIntent", "ICToggleStarIntent",
    "ICPlayPodcastIntent", "ICPlayEpisodeIntent",
    "ICPlayListIntent", "ICGetCurrentEpisodeIntent",
    "ICGetSleepTimerRemainingTimeIntent", "ICSetAutomaticSleepTimerIntent",
}
failures = []
for name in sorted(widget_controls | {"SmartListConfigIntent"}):
    if name not in metadata["widget"]:
        failures.append(f"Widget intent missing: {name}")
for name, definition in metadata["widget"].items():
    if definition["isDiscoverable"]:
        failures.append(f"Widget intent leaked into Shortcuts: {name}")
for name in sorted(public_controls):
    if not metadata["app"].get(name, {}).get("isDiscoverable", False):
        failures.append(f"Public Shortcuts action missing or hidden: {name}")

# Summary keys are generated by AppIntents as ${parameter}, not Swift source
# interpolation. Check the compiled contract so a source-only scan cannot
# accidentally bless unreachable translations or lose a parameter in German.
for language in ("en", "de"):
    strings = json.loads(subprocess.check_output([
        "plutil", "-convert", "json", "-o", "-",
        str(app / f"{language}.lproj/Localizable.strings"),
    ]))
    for name, definition in metadata["app"].items():
        summary = definition.get("actionConfiguration", {}).get("actionSummary", {}).get("wrapper", {}).get("summaryString", {}).get("formatString")
        if not summary:
            continue
        if summary not in strings:
            failures.append(f"{language} summary translation missing for {name}: {summary}")
        elif sorted(re.findall(r"\$\{[^}]+\}", summary)) != sorted(re.findall(r"\$\{[^}]+\}", strings[summary])):
            failures.append(f"{language} summary parameters differ for {name}")

result = {
    "command": shlex.join([sys.executable, *sys.argv]),
    "environment": platform.platform(), "artifacts": paths,
    "expected": "Widget intents remain exported and hidden; app controls remain discoverable",
    "actions": {group: {name: {"title": item["title"]["key"],
                               "isDiscoverable": item["isDiscoverable"]}
                         for name, item in actions.items()}
                for group, actions in metadata.items()},
    "failures": failures, "passed": not failures,
}
args.evidence.parent.mkdir(parents=True, exist_ok=True)
args.evidence.write_text(json.dumps(result, indent=2) + "\n")
for failure in failures:
    print("FAIL:", failure)
if failures:
    raise SystemExit(1)
print("PASS: Widget intents hidden; public playback actions and widget definitions retained")
